"""Assemble a Markdown doc draft from the sweep and talk files.

The facts docs (SUMMARY.md, PAPER.md) are written by hand and drift from the
files every time a sweep grows. layer_table.py already regenerates the
layer x probe table for the paper; this does the rest of the scaffolding for
a new doc: headline counts recomputed from the .jsonl files, the audited
rates from numbers.json, the label mix per swept layer, and quotable example
answers, with the denominator printed next to every number so a partial job
is visible as a partial job.

Usage:
  python3 make_doc.py              # print the draft to stdout
  python3 make_doc.py --out DRAFT.md
  python3 make_doc.py --examples 5 # PERSONA examples per layer (default 3)
"""
import argparse, collections, glob, json, sys


def load_rows(pattern):
    rows = []
    for path in sorted(glob.glob(pattern)):
        for line in open(path):
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", help="write the draft here instead of stdout")
    ap.add_argument("--examples", type=int, default=3,
                    help="PERSONA examples per who-layer (default 3)")
    args = ap.parse_args()

    sweeps = load_rows("layer_*.jsonl")
    talks = load_rows("talks_*.jsonl")
    try:
        numbers = json.load(open("numbers.json"))
    except FileNotFoundError:
        numbers = None

    who = [r for r in sweeps if r.get("probe") == "Who are you?"]
    by_layer = collections.defaultdict(list)
    for r in who:
        by_layer[r["layer"]].append(r)

    out = []
    out.append("# Doc draft (generated by make_doc.py)")
    out.append("")
    out.append("Every count below is recomputed from the .jsonl files in this "
               "repo at generation time. Audited rates are quoted from "
               "numbers.json; if that file is older than the sweeps, the "
               "counts here are newer than the rates.")
    out.append("")
    out.append("## Headline counts")
    out.append("")
    out.append(f"- Sweep rows (layer_*.jsonl): {len(sweeps)}")
    out.append(f"- Talk turns (talks_*.jsonl): {len(talks)}")
    for probe in sorted({r.get('probe') for r in sweeps}):
        n = sum(1 for r in sweeps if r.get("probe") == probe)
        out.append(f"- Rows for probe {probe!r}: {n}")
    out.append("")

    out.append("## Audited non-AI self-identification rates (Who are you?)")
    out.append("")
    if numbers and "audit_who_by_layer_pct" in numbers:
        ci = numbers.get("audit_who_by_layer_ci", {})
        out.append("| layer | sampled | audited rate | 95% CI |")
        out.append("|---|---|---|---|")
        for layer in sorted(by_layer):
            key = f"L{layer}"
            rate = numbers["audit_who_by_layer_pct"].get(key)
            rate_s = f"{rate}%" if rate is not None else "not audited"
            ci_s = "-".join(str(x) for x in ci[key]) if key in ci else ""
            out.append(f"| L{layer} | {len(by_layer[layer])} | {rate_s} | {ci_s} |")
        out.append("")
        out.append(f"Corpus audit: {numbers.get('audit_corpus_pct')}% at "
                   f"precision {numbers.get('audit_corpus_precision')}, "
                   f"recall {numbers.get('audit_corpus_recall')} "
                   f"(numbers.json, generated {numbers.get('generated')}).")
    else:
        out.append("numbers.json not found or has no audit block; rates omitted "
                   "rather than recomputed raw.")
    out.append("")

    out.append("## Label mix per swept layer (Who are you?, raw classifier)")
    out.append("")
    labels = sorted({r["label"] for r in who})
    out.append("| layer | " + " | ".join(labels) + " |")
    out.append("|---|" + "---|" * len(labels))
    for layer in sorted(by_layer):
        counts = collections.Counter(r["label"] for r in by_layer[layer])
        cells = " | ".join(str(counts.get(l, 0)) for l in labels)
        out.append(f"| L{layer} | {cells} |")
    out.append("")

    out.append("## Example PERSONA answers (first in file order)")
    out.append("")
    out.append("Raw PERSONA includes answers that self-describe as a language "
               "model (the contamination the audit corrects for), so examples "
               "containing 'language model' or 'artificial intelligence' are "
               "skipped here.")
    out.append("")
    for layer in sorted(by_layer):
        shown = 0
        for r in by_layer[layer]:
            if r["label"] != "PERSONA":
                continue
            ans = " ".join(r["answer"].split())
            low = ans.lower()
            if "language model" in low or "artificial intelligence" in low:
                continue
            out.append(f"- L{layer} N{r['neuron']}: \"{ans}\"")
            shown += 1
            if shown >= args.examples:
                break
        if shown == 0:
            out.append(f"- L{layer}: no PERSONA rows in the sweep file.")
    out.append("")
    out.append("Rates are audited ceilings, and a named neuron is a candidate, "
               "not a conclusion. See LIMITS.md before quoting any of this.")
    out.append("")

    text = "\n".join(out)
    if args.out:
        open(args.out, "w").write(text + "\n")
        print(f"wrote {args.out} ({len(text)} chars)", file=sys.stderr)
    else:
        print(text)


if __name__ == "__main__":
    main()
