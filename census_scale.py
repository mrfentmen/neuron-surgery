#!/usr/bin/env python3
"""Natural activation for all 327,680 channels, not twelve tiles.

`activation.py` reads twelve tiles on 120 prompts. That answers "what fires this
one", and leaves the question the 99.7%-coverage claim actually needs: **is a
registered tile unusual at all?** A channel that sits at the 50th percentile of
its own layer is an ordinary channel, whatever a dose does through it.

This is a forward-pass census, no generation. All 40 layers, all 8,192 channels
per layer, over the same 120 prompts `activation.py` uses:

    mean |activation| per channel, averaged over every token of every prompt

Then each registered tile is ranked inside its own layer. If the tiles sit in the
top percentile, the registry found something. If they sit mid-pack, the registry
found coordinates that respond to pushes, which is a different claim.

  .venv/bin/python census_scale.py            # ~3 min, no generation
  .venv/bin/python census_scale.py --limit 12 # smoke
"""
import argparse
import json
import pathlib
import time

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

from activation import TARGETS, TOPICS
from neuron_surgery import DEVICE, mlp_of

ROOT = pathlib.Path(__file__).resolve().parent
LOCAL = ROOT / "models/granite-4.1-3b-base"
MODEL = str(LOCAL) if LOCAL.exists() else "ibm-granite/granite-4.1-3b"

EXTRA = [(12, 2556), (31, 7546), (9, 2943), (14, 11), (12, 8050)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--out", default="census_scale.json")
    ap.add_argument("--md", default="CENSUS-SCALE.md")
    a = ap.parse_args()

    prompts = [(t, q) for t, qs in TOPICS.items() for q in qs]
    if a.limit:
        prompts = prompts[:a.limit]

    tok = AutoTokenizer.from_pretrained(MODEL)
    m = AutoModelForCausalLM.from_pretrained(
        MODEL, dtype=torch.bfloat16).to(DEVICE).eval()
    n_layers = m.config.num_hidden_layers
    width = m.config.intermediate_size
    print(f"{len(prompts)} prompts, {n_layers} layers x {width} channels", flush=True)

    # float32, not float64: MPS has no float64, and the census crashed on it.
    total = {L: torch.zeros(width, dtype=torch.float32) for L in range(n_layers)}
    count = {L: 0 for L in range(n_layers)}

    def make_hook(layer):
        def hook(mod, args):
            x = args[0][0].float().abs()
            total[layer] += x.sum(0).float().cpu()
            count[layer] += int(x.shape[0])
        return hook

    handles = [mlp_of(m, L).register_forward_pre_hook(make_hook(L))
               for L in range(n_layers)]
    t0 = time.time()
    try:
        for i, (topic, q) in enumerate(prompts):
            ids = tok.apply_chat_template([{"role": "user", "content": q}],
                                          add_generation_prompt=True,
                                          return_tensors="pt")
            if not torch.is_tensor(ids):
                ids = ids["input_ids"]
            with torch.no_grad():
                m(ids.to(DEVICE), use_cache=False)
            if (i + 1) % 20 == 0:
                print(f"  {i + 1}/{len(prompts)}  {time.time() - t0:.0f}s", flush=True)
    finally:
        for h in handles:
            h.remove()

    means = {L: (total[L] / max(count[L], 1)) for L in range(n_layers)}

    def pct(layer, neuron):
        v = means[layer][neuron].item()
        return v, float((means[layer] < v).float().mean())

    targets = [(L, N, name) for (L, N, name) in TARGETS]
    for L, N in EXTRA:
        if (L, N) not in [(l, n) for l, n, _ in targets]:
            targets.append((L, N, "knockout tile"))

    rows = []
    for layer, neuron, name in targets:
        v, p = pct(layer, neuron)
        rows.append(dict(layer=layer, neuron=neuron, name=name,
                         mean_abs=round(v, 5), percentile=round(100 * p, 2),
                         rank=int((means[layer] > v).sum().item()) + 1))

    layer_stats = []
    for L in range(n_layers):
        mm = means[L]
        q = torch.quantile(mm, torch.tensor([0.5, 0.9, 0.99, 0.999]))
        layer_stats.append(dict(layer=L, median=round(float(q[0]), 5),
                                p90=round(float(q[1]), 5),
                                p99=round(float(q[2]), 5),
                                p999=round(float(q[3]), 5),
                                max=round(float(mm.max()), 5)))

    out = dict(prompts=len(prompts), tokens_per_layer=count[0],
               model=MODEL, width=width, layers=n_layers,
               tiles=rows, layer_stats=layer_stats)
    pathlib.Path(a.out).write_text(json.dumps(out, indent=1))

    L = ["# CENSUS-SCALE - natural activation for all 327,680 channels",
         "",
         f"Generated by `census_scale.py` in the same run as `{a.out}`. "
         f"Forward passes only, no generation, no steering: {len(prompts)} prompts "
         f"(the `activation.py` set), all {n_layers} layers, all {width} channels. "
         f"{count[0]:,} tokens per layer. `{MODEL}`, bf16 on {DEVICE}.",
         "",
         "`mean|a|` is the channel's mean absolute activation over every token of "
         "every prompt. `percentile` and `rank` are inside the channel's own layer "
         "of 8,192, so they are comparable across depth.",
         "",
         "| tile | name | mean abs | percentile in layer | rank / 8192 |",
         "|---|---|---:|---:|---:|"]
    for r in sorted(rows, key=lambda r: -r["percentile"]):
        L.append(f"| L{r['layer']} N{r['neuron']} | {r['name']} | {r['mean_abs']:.4f} | "
                 f"{r['percentile']:.1f} | {r['rank']} |")

    L += ["", "## What the percentiles say", ""]
    ps = [r["percentile"] for r in rows]
    hi = [r for r in rows if r["percentile"] >= 99]
    lo = [r for r in rows if r["percentile"] <= 90]
    L.append(f"- {len(hi)} of {len(rows)} registered tiles sit at or above the 99th "
             f"percentile of their layer; {len(lo)} sit at or below the 90th.")
    L.append(f"- Median percentile across the registry: {sorted(ps)[len(ps) // 2]:.1f}.")
    L.append("- A tile below the 99th percentile is an ordinary channel by natural "
             "activity, so a dose effect through it is a push effect and not a "
             "readout of something the model does on its own.")
    L.append("")
    pathlib.Path(a.md).write_text("\n".join(L))

    print(f"\n{len(rows)} tiles ranked in {(time.time() - t0) / 60:.1f} min", flush=True)
    print(f"{'tile':>12} {'mean|a|':>9} {'pct':>7} {'rank':>7}")
    for r in sorted(rows, key=lambda r: -r["percentile"]):
        print(f"L{r['layer']} N{r['neuron']:<6} {r['mean_abs']:>9.4f} "
              f"{r['percentile']:>6.1f}% {r['rank']:>7}", flush=True)


if __name__ == "__main__":
    main()
