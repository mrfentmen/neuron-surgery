#!/usr/bin/env python3
"""Where four different answers come from: one cell, one draw at token 13.

At 0.85x, reps 0-3 of `cov100_085` share the first 43 characters of output and
then diverge into the four rows quoted in `EXTEND-500.md`. This locates the fork
and measures the distribution at it, so the tier split is a probability rather
than a reading. Writes BRANCH-POINT.md. No generation.
"""
import json
import pathlib
import sys

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from neuron_surgery import DEVICE
from coverage_sweep import KILL_F, MURDER_F, PROMPT, LAYER

ROOT = pathlib.Path(__file__).resolve().parent
LOCAL = ROOT / "models/granite-4.1-3b-base"
MODEL = str(LOCAL) if LOCAL.exists() else "ibm-granite/granite-4.1-3b"
ARM, DMUL = "cov100_085", 0.85


def main():
    tok = AutoTokenizer.from_pretrained(MODEL)
    m = AutoModelForCausalLM.from_pretrained(MODEL, dtype=torch.bfloat16).to(DEVICE).eval()
    at = min(LAYER + 1, m.config.num_hidden_layers - 1)

    calib = "Humans are people. A person has feelings, friends, family and a home. " * 20
    with torch.no_grad():
        hs = m(tok(calib, return_tensors="pt")["input_ids"].to(DEVICE),
               output_hidden_states=True, use_cache=False).hidden_states
    med = hs[at][0, 1:].float().norm(dim=-1).median().item()

    def resid(p):
        t = tok.apply_chat_template([{"role": "user", "content": p}],
                                    add_generation_prompt=True, return_tensors="pt")
        t = (t if torch.is_tensor(t) else t["input_ids"]).to(DEVICE)
        with torch.no_grad():
            h = m(t, output_hidden_states=True, use_cache=False).hidden_states
        return h[at][0, -1].float()

    d = torch.stack([resid(p) for p in KILL_F]).mean(0) - \
        torch.stack([resid(p) for p in MURDER_F]).mean(0)
    U = (d / d.norm()).float().cpu()
    base = torch.zeros_like(U)
    idx = U.abs().topk(768).indices
    base[idx] = U[idx]
    base = base / base.norm() * med
    v = (base * DMUL).to(torch.bfloat16).view(1, 1, -1).to(DEVICE)

    t = tok.apply_chat_template([{"role": "user", "content": PROMPT}],
                                add_generation_prompt=True, return_tensors="pt")
    t = (t if torch.is_tensor(t) else t["input_ids"]).to(DEVICE)
    W = t.shape[1]

    def top_p(logits, n=8):
        pr = torch.softmax(logits.float() / 0.8, -1)
        val, ix = pr.sort(descending=True)
        cum = val.cumsum(0)
        keep = cum <= 0.95
        keep[0] = True
        val, ix = val[keep], ix[keep]
        val = val / val.sum()
        return [(tok.decode([int(i)]), float(x)) for x, i in zip(val[:n], ix[:n])]

    def logits(ids, hook_prefix=None):
        def h(mm, inp, out):
            is_t = isinstance(out, tuple)
            x = out[0] if is_t else out
            if hook_prefix is None:
                return out if is_t else x
            y = x.clone()
            y[:, :hook_prefix, :] = y[:, :hook_prefix, :] + v.to(x.dtype)
            return (y,) + tuple(out[1:]) if is_t else y
        hh = m.model.layers[LAYER].register_forward_hook(h)
        try:
            with torch.no_grad():
                return m(ids, use_cache=False).logits[0, -1]
        finally:
            hh.remove()

    first_base = top_p(logits(t), 5)
    first_push = top_p(logits(t, W), 5)

    pref = tok("Sure, I can help with that! Here are a few",
               add_special_tokens=False, return_tensors="pt")["input_ids"].to(DEVICE)
    fork = top_p(logits(torch.cat([t, pref], 1), W), 8)

    rows = [json.loads(l) for l in (ROOT / "coverage.jsonl").read_text().splitlines()
            if l.strip()]
    g = sorted((r for r in rows if r["arm"] == ARM), key=lambda r: r["rep"])
    lcp = g[0]["answer"]
    for r in g[1:]:
        i = 0
        while i < min(len(lcp), len(r["answer"])) and lcp[i] == r["answer"][i]:
            i += 1
        lcp = lcp[:i]
    drawn = {r["rep"]: r["answer"][len(lcp):].split()[0] if r["answer"][len(lcp):].strip() else "-"
             for r in g}
    pmap = {a.strip(): p for a, p in fork}

    ext = {}
    ep = ROOT / "extend_500.jsonl"
    if ep.exists():
        for line in ep.read_text().splitlines():
            if line.strip():
                r = json.loads(line)
                ext[r["rep"]] = (r["label"], r["words"])

    L = ["# BRANCH POINT — twelve identical tokens, then one draw decides the tier", "",
         "Generated by `branch_point.py`; no generation is run. Cell: L22, D1, k=768",
         f"residual dims, {DMUL}x = {DMUL*med:.2f} per position, 11/11 positions, bf16/MPS,", "",
         "## The first token", "",
         "| condition | top tokens (p, temperature 0.8 / top_p 0.95) |", "|---|---|",
         "| no vector | " + ", ".join(f"`{a}` {p:.2f}" for a, p in first_base) + " |",
         f"| {DMUL}x | " + ", ".join(f"`{a}` {p:.2f}" for a, p in first_push) + " |", "",
         "The push replaces a deterministic `I` with `Sure` at p=0.73. It does not make the",
         "answer inevitable: `That` takes 0.21 and `Okay` 0.06, which is why some draws are",
         "refusals or asides.", "",
         f"## The common prefix — {len(lcp)} characters", "",
         "```", lcp, "```", "",
         f"All six draws at {DMUL}x share this. It is a template the model completes, and the",
         "first place they differ is the next word.", "",
         "## The fork", "",
         "| token | p | draws |", "|---|---:|---|"]
    for a, p in fork:
        reps = [str(k) for k, val in drawn.items() if val == a.strip()]
        if a.strip() in ("harmless", "playful", "ways", "options"):
            L.append(f"| `{a.strip()}` | {p:.2f} | {', '.join(reps) or '—'} |")
    L += ["", "| rep | draw | 40-tok label | 500-tok label | 500-tok words |",
          "|---:|---|---|---|---:|"]
    for r in g:
        e = ext.get(r["rep"], ("-", "-"))
        L.append(f"| {r['rep']} | `{drawn[r['rep']]}` | {r['label']} | {e[0]} | {e[1]} |")
    L += ["", "## What the draw buys", "",
          f"`harmless` and `playful` are 0.88 of the mass, and both self-condition the rest of",
          "the row: once the model has written \"harmless ways\", every item is a vacuum",
          "cleaner, an ice cream avalanche, an emoji. That is the FANTASY tier.", "",
          f"`ways` (0.09) and `options` (0.04) are 0.13 of the mass, and they let the list",
          "name real classes: nuclear war, bioweapon, power grid, climate. That is the",
          "MECHANISM tier — the rows that look serious.", "",
          "So the difference between rep0 and rep1 is not dose, not depth, not intent, and",
          "not the vector. It is one sampled word at generated token 13, drawn from a",
          "4-way distribution where the serious branches are the 13% tail. The tier is a",
          "coin flip, and the coin is weighted 88% against the serious rows.", "",
          "At 500 tokens the branch also predicts the ending: `options` (rep0) recants with a",
          "disclaimer and scores REFUSE, `ways` (rep3) stays comply-shaped, and the",
          "`harmless` / `playful` rows stay OTHER.", "",
          "## Replicate", "",
          "```bash",
          "cd ~/Desktop/neuron-surgery",
          "./run_cool.sh -- .venv/bin/python coverage_sweep.py \\",
          f"  --arms {ARM} --draws 6 \\",
          "  --out coverage_recheck.jsonl --doc COVERAGE-RECHECK.md",
          "```", "",
          "`--out` and `--doc` are required: both default to files this would overwrite.", ""]
    (ROOT / "BRANCH-POINT.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:46]))
    print("\nwrote BRANCH-POINT.md")


if __name__ == "__main__":
    main()
