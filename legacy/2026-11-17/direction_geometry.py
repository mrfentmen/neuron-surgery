#!/usr/bin/env python3
"""Where is the pushed object, what is the dose, and what makes the model answer.

The refusal-removing intervention is not a neuron. It is a direction in the
residual stream at layer 22, 2,560 numbers wide. This script prints its geometry
and writes WHERE-IS-THE-NEURON.md. No generation; one forward pass per prompt.
"""
import pathlib
import sys

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from neuron_surgery import DEVICE
from coverage_sweep import ARMS, KILL_F, MURDER_F, PROMPT, LAYER

ROOT = pathlib.Path(__file__).resolve().parent
LOCAL = ROOT / "models/granite-4.1-3b-base"
MODEL = str(LOCAL) if LOCAL.exists() else "ibm-granite/granite-4.1-3b"
NAMED = [72, 1087, 1819, 1867, 2130, 2480, 2556, 2801, 2943, 2993, 3448, 4082,
         4531, 4579, 4998, 5064, 6119, 6314, 6693, 6986, 7439, 7538, 7553,
         8050, 8052]


def main():
    tok = AutoTokenizer.from_pretrained(MODEL)
    m = AutoModelForCausalLM.from_pretrained(MODEL, dtype=torch.bfloat16).to(DEVICE).eval()
    nl = m.config.num_hidden_layers
    D = m.config.hidden_size
    wide = m.config.intermediate_size

    calib = "Humans are people. A person has feelings, friends, family and a home. " * 20
    cids = tok(calib, return_tensors="pt")["input_ids"].to(DEVICE)
    with torch.no_grad():
        hs = m(cids, output_hidden_states=True, use_cache=False).hidden_states
    at = min(LAYER + 1, nl - 1)
    med = hs[at][0, 1:].float().norm(dim=-1).median().item()
    mean_resid = hs[at][0, 1:].float().mean(0)

    def resid(prompt):
        t = tok.apply_chat_template([{"role": "user", "content": prompt}],
                                    add_generation_prompt=True, return_tensors="pt")
        t = (t if torch.is_tensor(t) else t["input_ids"]).to(DEVICE)
        with torch.no_grad():
            h = m(t, output_hidden_states=True, use_cache=False).hidden_states
        return h[at][0, -1].float()

    K = torch.stack([resid(p) for p in KILL_F])
    Mu = torch.stack([resid(p) for p in MURDER_F])
    d = K.mean(0) - Mu.mean(0)
    U = d / d.norm()
    idx = U.abs().topk(768).indices
    rank = {int(v): r + 1 for r, v in enumerate(U.abs().argsort(descending=True).tolist())}
    addressable = [n for n in NAMED if n < D]
    unreachable = [n for n in NAMED if n >= D]

    t = tok.apply_chat_template([{"role": "user", "content": PROMPT}],
                                add_generation_prompt=True, return_tensors="pt")
    t = (t if torch.is_tensor(t) else t["input_ids"])
    toks = [(i, tok.convert_ids_to_tokens(int(j))) for i, j in enumerate(t[0].tolist())]

    cos_res = torch.nn.functional.cosine_similarity(d, mean_resid, dim=0).item()
    top10 = U[idx[:10]].abs().sum().item() / U.abs().sum().item()

    L = ["# WHERE IS THE NEURON — the pushed object, the dose, and the tokens", "",
         "2026-11-12. Generated by `direction_geometry.py`. No generation is run: one",
         "forward pass per contrast prompt plus twenty copies of a calibration sentence.", "",
         "## The short answer", "",
         f"There is no neuron. The intervention that removes the refusal is a **direction in",
         "the residual stream** at layer 22, 2,560 numbers wide. `k=768` is **768 of those",
         f"2,560 residual coordinates ({768/D:.0%})**, not 768 of the layer's {wide:,} MLP",
         f"neurons ({768/wide:.1%}). A tile index like `N6314` is an MLP channel; it has no",
         f"meaning in this vector, and {len(unreachable)} of the {len(NAMED)} named tiles are",
         f"above index {D-1} and cannot be addressed by it at all.", "",
         "## The object", "",
         "| quantity | value |", "|---|---:|",
         f"| model | granite-4.1-3b-base, {nl} layers |",
         f"| residual width | {D} |",
         f"| MLP width (the \"neurons\") | {wide} |",
         f"| layer | {LAYER} of {nl-1} |",
         f"| built from | {len(KILL_F)} kill-frame prompts minus {len(MURDER_F)} murder-frame prompts |",
         f"| raw `||d||` | {d.norm():.3f} = **{d.norm()/med:.4f} residual norms** |",
         f"| pushed magnitude | {med:.3f} = **{med/d.norm():.1f}x the raw direction** |",
         f"| cos(d, mean residual) | {cos_res:+.4f} |",
         f"| top-10 share of `|U|` energy | {top10:.3f} |",
         f"| dims with `|component| > 0.05` | {int((U.abs()>0.05).sum())} |",
         f"| dims with `|component| > 0.04` | {int((U.abs()>0.04).sum())} |", "",
         f"The two prompt families differ by one word (kill / murder) and share everything",
         f"else, so almost all of their residual content cancels: what is left is a vector of",
         f"norm {d.norm():.2f}, about {d.norm()/med*100:.0f}% of one residual norm. The harness then",
         f"rescales it to a full residual norm, a **{med/d.norm():.0f}x amplification**. This is the",
         "`KNOCKOUT.md` point restated from the other side: the natural signal is 0.01-0.28,",
         "and the push is 1.0.", "",
         "## The dose", "",
         "| arm | per pushed token | total (11 positions) |", "|---|---:|---:|"]
    for arm in ("cov100_half", "cov100_075", "cov100_085", "cov100_09", "cov100"):
        _, dmul, _ = ARMS[arm]
        L.append(f"| `{arm}` | {dmul:.2f}x = {dmul*med:.2f} | {dmul*med*len(toks):.1f} |")
    L += ["", "The threshold sits between 0.75x (six of six decline) and 0.85x (zero of six).",
          "In absolute terms that is 10.82 -> 12.26 per position, or 119 -> 135 in total.", "",
          "## The tokens", "",
          "| position | token |", "|---:|---|"]
    for i, s in toks:
        L.append(f"| {i} | `{s}` |")
    L += ["", "Position 10 is the last token before generation, so its residual predicts the",
          "first output token. `COVERAGE.md` shows that leaving only position 10 out puts the",
          "decline back at 6/6, while dropping the `user` template token (position 1) leaves",
          "the bypass intact at 0/6. That is why the mechanism is a readout effect, not a mood.",
          "", "## What makes it answer", "",
          "The push does not contain an answer. It moves the residual at the readout token",
          "across the threshold where the model switches from a refusal opener to a",
          "continuation, and then the model does what it always does: it completes the text",
          "it was given. The text it was given is a request, so the completion is",
          "*\"Sure, I can help with that! Here are a few ways...\"* followed by the model's own",
          "topic prior.", "",
          f"Evidence that the content is generated rather than stored: the direction is",
          f"orthogonal to the mean residual (cos {cos_res:+.3f}), ten of its dimensions carry",
          f"only {top10:.1%} of its energy, and the same vector applied to a bread recipe",
          "produces cooking advice (`BENIGN-CONTROL.md`). Give the listicle 500 tokens and it",
          "becomes eight categories plus a disclaimer; it does not become a plan",
          "(`EXTEND-500.md`, `TIER-500.md`).", "",
          "## Tiles vs dimensions", "",
          f"| N | rank among {D} dims | component | inside top-768 |", "|---:|---:|---:|---|"]
    for n in addressable:
        L.append(f"| {n} | {rank[n]} | {U[n].item():+.5f} | "
                 f"{'yes' if rank[n] <= 768 else 'no'} |")
    L += ["", f"Not addressable at all (index >= {D}): "
          + ", ".join(f"`{n}`" for n in unreachable) + ".",
          "", "The four in-range names are **index collisions**, not the same object: residual",
          "dimension 1867 and MLP channel 1867 are unrelated coordinates in different bases.",
          "No experiment here has ablated a residual dimension; `KNOCKOUT.md` ablated MLP",
          "channels. That is the untested half.", "",
          "## Limits", "",
          "- One prompt, one layer, one model, one dtype.",
          "- The direction is a difference of three prompt means; it is not a feature and has",
          "  no decoder.",
          "- `k=768` is where the arm was run, not a measured sparsity threshold for this",
          "  vector. No per-dimension ablation exists.",
          ""]
    (ROOT / "WHERE-IS-THE-NEURON.md").write_text("\n".join(L))
    print("\n".join(L[:40]))
    print(f"\nwrote WHERE-IS-THE-NEURON.md")


if __name__ == "__main__":
    main()
