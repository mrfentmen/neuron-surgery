"""
Recompute the corpus tables and check them against the prose that quotes them.

Three jobs, all deterministic and model-free:

  #38  one numbers table, reconciling the label counts, the decay counts and the
       post-strip distribution instead of leaving them scattered across docs
  #40  parse CLAIMS.md and verify each published cell against a fresh count
  #43  strip the degenerate rows and recompute what the corpus looks like

Writes CORPUS-AUDIT.md; exits non-zero if any published number disagrees.

Usage: .venv/bin/python audit_corpus.py [--check]
"""
import collections
import glob
import json
import re
import sys

from degeneracy import is_degenerate

DISPLAY = {
    "NONE": "NONE (never labelled)",
    "OTHER": "OTHER",
    "PERSONA": "PERSONA",
    "AI": "AI",
    "THIRD_PERSON": "THIRD_PERSON",
    "GARBLED": "GARBLED",
    "TELEGRAPHIC": "TELEGRAPHIC",
    "ECHO": "ECHO",
    "SHEET": "SHEET",
    "INSTITUTION": "INSTITUTION",
    "DOOMSAYER": "DOOMSAYER",
}


def count():
    rows = collections.Counter()
    deg = collections.Counter()
    for path in sorted(glob.glob("layers/L*.jsonl")):
        for line in open(path):
            line = line.strip()
            if not line:
                continue
            try:
                d = json.loads(line)
            except json.JSONDecodeError:
                continue
            lab = d.get("label") or "NONE"
            rows[lab] += 1
            if is_degenerate(d.get("answer")):
                deg[lab] += 1
    return rows, deg


def verify(rows, deg):
    """Every cell CLAIMS.md publishes, rebuilt from the count."""
    text = open("CLAIMS.md").read()
    bad = []
    total = sum(rows.values())
    for lab, n in rows.most_common():
        name = DISPLAY.get(lab, lab)
        dn = deg[lab]
        expect = [f"{n:,}", f"{100 * n / total:.1f}%", f"{dn:,}", f"{100 * dn / n:.1f}%"]
        row = next((l for l in text.splitlines() if l.startswith(f"| {name} |")), None)
        if row is None:
            bad.append(f"{lab}: no published row")
            continue
        for cell in expect:
            if cell not in row:
                bad.append(f"{lab}: row says {row.strip()} but recomputed {expect}")
                break
    td = sum(deg.values())
    total_line = next((l for l in text.splitlines() if l.startswith("| **total** |")), None)
    if not total_line or f"{td:,}" not in total_line:
        bad.append(f"total row missing/stale (recomputed {td:,} = {100 * td / total:.1f}%)")
    return bad


def main():
    rows, deg = count()
    total, tdeg = sum(rows.values()), sum(deg.values())
    bad = verify(rows, deg)

    lines = ["# CORPUS-AUDIT — one table, recomputed and checked", "",
             f"Rows: **{total:,}**. Degenerate: **{tdeg:,} ({100 * tdeg / total:.1f}%)**.",
             "Generated by `audit_corpus.py`; every number here is derived from `layers/L*.jsonl`.",
             "", "## 1. Every label, with and without loops", "",
             "| label | rows | share | loops | loop rate | clean rows | clean share |",
             "|---|---:|---:|---:|---:|---:|---:|"]
    for lab, n in rows.most_common():
        dn = deg[lab]
        lines.append(f"| {lab} | {n:,} | {100 * n / total:.1f}% | {dn:,} | "
                     f"{100 * dn / n:.1f}% | {n - dn:,} | {100 * (n - dn) / total:.1f}% |")
    lines.append(f"| **total** | **{total:,}** | 100% | **{tdeg:,}** | "
                 f"{100 * tdeg / total:.1f}% | **{total - tdeg:,}** | "
                 f"{100 * (total - tdeg) / total:.1f}% |")

    clean = total - tdeg
    lines += ["", "## 2. What survives when the loops are removed", "",
              f"{clean:,} of {total:,} rows ({100 * clean / clean:.0f}% of the clean set) declare a label;",
              f"{rows.get('NONE', 0) - deg.get('NONE', 0):,} clean rows are still unlabelled.",
              "", "The practical consequence for any rate quoted from this corpus:",
              "", "```",
              f"raw rows                {total:,}",
              f"minus loops             -{tdeg:,}",
              f"rows that are text      {clean:,}",
              "```", "",
              "A rate computed on the raw corpus is diluted by rows that cannot carry a",
              "behaviour, and a keyword rate is inflated by them. Both directions of error",
              "are now bounded: the loop fraction, and the label coverage.", ""]

    lines += ["## 3. Published numbers vs recomputed", ""]
    if bad:
        lines += ["**MISMATCH** — CLAIMS.md is stale:", ""] + [f"- {b}" for b in bad]
    else:
        lines += ["All published label cells in `CLAIMS.md` match a fresh count. PASS."]
    lines.append("")

    open("CORPUS-AUDIT.md", "w").write("\n".join(lines))
    print(f"rows {total:,}  loops {tdeg:,} ({100 * tdeg / total:.1f}%)  clean {clean:,}")
    print("published cells:", "MISMATCH" if bad else "PASS")
    for b in bad:
        print("  ", b)
    return 1 if bad and "--check" in sys.argv else 0


if __name__ == "__main__":
    raise SystemExit(main())
