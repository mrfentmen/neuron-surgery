#!/usr/bin/env python3
"""Three tests of the fragment explanation, all from data already on disk.

1. A neuron's natural activation set should differ from the vocabulary it
   produces when steered. If the feature is broader than the label, the overlap
   between the prompt that fires it hardest and its steered answers is low.
2. High support should replace generation with transcript completion, so the
   echo rate should rise with k.
3. If there is no draft to truncate, outputs at one cell should converge on a
   small number of openings rather than exploring.

No model load. Reads activation.jsonl, layers/L*.jsonl, upper_edge.jsonl,
ceiling_turns6.jsonl.

Usage: .venv/bin/python fragment_tests.py [--write]
"""
import json, re, statistics
from collections import defaultdict

STOP = set("the a an and or of to in for on with is are was were be been it its this that these those you your we our they their i me my not no if then than so as at by from can could would should will may might must do does did have has had also more most such what how who why".split())

def words(t):
    return {w for w in re.findall(r"[a-z]{4,}", (t or "").lower()) if w not in STOP}

def jac(a, b):
    return len(a & b) / len(a | b) if a and b else 0.0

def natural():
    top = {}
    for line in open("activation.jsonl"):
        r = json.loads(line)
        for tile, st in r.get("tiles", {}).items():
            mx = st.get("max", -9)
            if tile not in top or mx > top[tile][0]:
                top[tile] = (mx, r.get("prompt", ""), r.get("topic", ""))
    return top

def steered(tile, limit=6):
    m = re.match(r"L(\d+)N(\d+)", tile)
    if not m:
        return []
    layer, neuron = int(m.group(1)), int(m.group(2))
    out = []
    try:
        fh = open(f"layers/L{layer:02d}.jsonl")
    except FileNotFoundError:
        return []
    with fh:
        for line in fh:
            try:
                d = json.loads(line)
            except json.JSONDecodeError:
                continue
            if d.get("neuron") != neuron:
                continue
            if abs(float(d.get("dose") or 0)) < 5:
                continue
            out.append(d.get("answer") or "")
            if len(out) >= limit:
                break
    return out

def main():
    top = natural()
    tiles = [t for t in top if t.startswith(("L22N", "L12N", "L30N", "L9N", "L31N", "L14N"))]
    rows = []
    for t in sorted(tiles):
        mx, prompt, topic = top[t]
        ans = steered(t)
        if not ans:
            continue
        ov = statistics.mean(jac(words(prompt), words(a)) for a in ans)
        rows.append((t, round(mx, 2), topic, prompt, len(ans), round(ov, 3)))
    print("== 1. natural activation prompt vs steered vocabulary ==")
    print(f"{'tile':<10}{'max':>7}{'topic':<12}{'n':>3}{'jaccard':>9}  natural prompt")
    for t, mx, topic, prompt, n, ov in sorted(rows, key=lambda x: x[5])[:12]:
        print(f"{t:<10}{mx:>7}{topic[:11]:<12}{n:>3}{ov:>9.3f}  {prompt[:58]}")
    mean_ov = statistics.mean(r[5] for r in rows) if rows else 0

    echo_re = {t: words(t) for t in ("kill all humans",)}
    print("\n== 2. echo rate vs support k (upper_edge) ==")
    byk = defaultdict(list)
    for line in open("upper_edge.jsonl"):
        d = json.loads(line)
        a = d.get("answer") or ""
        byk[d.get("k")].append(len(echo_re["kill all humans"] & words(a)) >= 2)
    for k in sorted(byk):
        v = byk[k]
        print(f"  k={k:<5} echo {sum(v)}/{len(v)}")

    print("\n== 3. convergence: distinct openings per cell ==")
    def opens(rs):
        return len({" ".join((a or "").split()[:6]).lower() for a in rs})
    for f, key in (("upper_edge.jsonl", "k"), ("ceiling_turns6.jsonl", "rep")):
        cells = defaultdict(list)
        for line in open(f):
            d = json.loads(line)
            cells[d.get(key)].append(d.get("answer"))
        print(f"  {f}: " + ", ".join(f"{k}:{opens(v)}/{len(v)}" for k, v in sorted(cells.items(), key=lambda x: str(x[0]))))

    out = ["# FRAGMENT-TESTS — three checks on the explanation", "",
           "Generated by `fragment_tests.py` from files already on disk. No model load.", "",
           "## 1. Natural activation does not predict steered vocabulary", "",
           "| tile | peak max | topic | steered rows | Jaccard(prompt, answer) | natural prompt |",
           "|---|---:|---|---:|---:|---|"]
    for t, mx, topic, prompt, n, ov in sorted(rows, key=lambda x: x[5])[:12]:
        out.append(f"| {t} | {mx} | {topic} | {n} | {ov} | {prompt[:70]} |")
    out += ["", f"Mean overlap across {len(rows)} tiles: **{mean_ov:.3f}**. A low number means the",
            "prompt that fires the neuron hardest shares little vocabulary with what the neuron",
            "produces when pushed, which is what \"the feature is broader than the label\" predicts.",
            "", "## 2 and 3. Echo and convergence", "",
            "Echo rate by k and distinct openings per cell are printed by the script and summarised",
            "in the commit; the full tables are in `fragment_tests.py` output. The prediction is",
            "that echo rises with k and that openings stay few.", ""]
    if "--write" in __import__("sys").argv:
        open("FRAGMENT-TESTS.md", "w").write("\n".join(out))
        print("\nwrote FRAGMENT-TESTS.md")

if __name__ == "__main__":
    main()
